<?php

declare(strict_types=1);

/**
 * Generate the endpoint coverage document from the DERIVED classification.
 *
 * Usage:
 *   php bin/generate-endpoint-coverage.php           # write the doc
 *   php bin/generate-endpoint-coverage.php --check   # exit 1 if stale
 *
 * Exit codes: 0 ok, 1 stale (with --check), 2 usage.
 *
 * Provenance: `bin/generate-relation-graph.php`, which does the same for
 * foreign keys and whose docblock explains why the measurement must be an
 * EXECUTED/parsed artifact rather than a text search. Nothing here transcribes
 * a constructor name: every row comes from `EndpointCoverage::classify()`.
 *
 * Every number in the generated document is measured HERE, from the parsed
 * scheme and the loaded catalog, at generation time. None is typed in.
 */

use MeRezaRezaei\Teleframe\Laravel\SchemaArtifacts;
use MeRezaRezaei\Teleframe\Schema\Generator\TlParser;
use MeRezaRezaei\Teleframe\Schema\Mirror\EndpointCoverage;
use MeRezaRezaei\Teleframe\Schema\Mirror\MirrorCatalog;

$root = dirname(__DIR__);
require $root.'/vendor/autoload.php';

// $argv[0] is THIS script's path, not an argument. The plan's sketch compared
// the raw $argv against ['--check'], which always contained the script path and
// therefore exited 2 on EVERY invocation — including --check, so the plan's own
// staleness gate could never have passed. Slice it off first.
$args = array_slice($argv, 1);

$check = in_array('--check', $args, true);
if (array_diff($args, ['--check']) !== []) {
    fwrite(STDERR, "usage: php bin/generate-endpoint-coverage.php [--check]\n");
    exit(2);
}

$tl = SchemaArtifacts::tl();
$scheme = TlParser::parseFile($tl);
$catalog = MirrorCatalog::load(SchemaArtifacts::catalog(), $scheme);
$report = EndpointCoverage::classify($scheme, $catalog);
$counts = $report->counts();

$byKind = [];
foreach ($report->endpoints() as $e) {
    $byKind[$e['kind']][] = $e;
}

// ── The universe, and why it is not the number `grep -c '^update'` prints ────
// Measured here, from the SAME scheme and the SAME TL bytes the classification
// walks, so the document can never disagree with the numbers above it.
$universe = 0;
foreach ($scheme->types() as $type) {
    foreach (array_keys($type->constructors()) as $name) {
        if (str_starts_with((string) $name, 'update')) {
            $universe++;
        }
    }
}

$updateTypeCtors = count($scheme->types()['Update']->constructors() ?? []);

$methodsNamedLikeUpdates = 0;
foreach (array_keys($scheme->methods()) as $name) {
    if (str_starts_with((string) $name, 'update')) {
        $methodsNamedLikeUpdates++;
    }
}

$tlLinesMatchingUpdatePrefix = 0;
foreach (file($tl) ?: [] as $line) {
    if (preg_match('/^update[A-Za-z0-9_.]+/', $line) === 1) {
        $tlLinesMatchingUpdatePrefix++;
    }
}

$catalogUpdateCtors = 0;
foreach ($catalog->tableNames() as $tfName) {
    foreach ($catalog->table($tfName)->ctors as $ctor) {
        if (str_starts_with((string) $ctor, 'update')) {
            $catalogUpdateCtors++;
        }
    }
}

$declaredNestedSources = count($catalog->nestedSources());

$out = [];
$out[] = '<!-- GENERATED FILE. Do not hand-edit. Run: php bin/generate-endpoint-coverage.php -->';
$out[] = '';
$out[] = '# MTProto endpoint coverage — every `update*` constructor, and what happens to it';
$out[] = '';
$out[] = 'Generated by `bin/generate-endpoint-coverage.php` from the parsed layer-227 scheme';
$out[] = '(`schema/sources/TL_telegram_v227.tl`) and the mirror catalog';
$out[] = '(`src/Schema/schema/mirror-catalog.json`). Nothing here is transcribed: every row is';
$out[] = 'derived by `EndpointCoverage::classify()`.';
$out[] = '';
$out[] = '## Why this document exists';
$out[] = '';
$out[] = 'This package stores Telegram history so that agents can act on it. A constructor whose';
$out[] = 'facts are silently dropped produces a crawl that completes, no error, and a database';
$out[] = 'missing rows — which is indistinguishable from "this account has none of those". This';
$out[] = 'document makes every constructor\'s fate explicit, so an absence is always a LABEL,';
$out[] = 'never a silence. The `unmodelled` population below is the project\'s real backlog.';
$out[] = '';
$out[] = '## The declared universe, and why it is not what `grep` says';
$out[] = '';
$out[] = 'The figure that started this work — '.sprintf('%d', $tlLinesMatchingUpdatePrefix).' — is a count of';
$out[] = '**LINES** in the TL file that begin with `update`, not a count of constructors. The';
$out[] = 'difference is exactly '.$methodsNamedLikeUpdates.' **methods** (';
$out[] = '`updates.getState`, `updates.getDifference`, `updates.getChannelDifference`), which are RPC';
$out[] = 'functions and can never be an endpoint.';
$out[] = '';
$out[] = '| population | count | what it is |';
$out[] = '|---|---:|---|';
$out[] = '| TL lines matching `^update` | '.$tlLinesMatchingUpdatePrefix.' | the figure usually quoted |';
$out[] = '| — of which METHODS, not constructors | '.$methodsNamedLikeUpdates.' | `updates.*` RPC functions |';
$out[] = '| **constructors named `update*` (the universe)** | **'.$universe.'** | every row below |';
$out[] = '| — of which constructors of type `Update` | '.$updateTypeCtors.' | the top-level update type |';
$out[] = '';
$out[] = 'Every constructor in the universe is classified exactly once. No constructor is excluded';
$out[] = 'to make a count agree; the per-kind counts below sum to '.$universe.', and';
$out[] = '`tests/Schema/EveryUpdateEndpointIsClassifiedTest.php` asserts that sum.';
$out[] = '';
$out[] = '## How to use this document';
$out[] = '';
$out[] = '1. Find the constructor under its `update*` name.';
$out[] = '2. Read its kind: `root-fact` and `nested-source` place rows in the named tables;';
$out[] = '   `log-only` and `unmodelled` reach `tf_updates` and nothing deeper. An `update-carrier`';
$out[] = '   is an RPC result whose `Vector<Update>` members must EACH be placed under their own';
$out[] = '   constructor; an `rpc-result` carries no update and owes no row at all.';
$out[] = '3. For an `unmodelled` ctor, the reason names the missing artifact — add the ctor to a';
$out[] = '   catalog entry\'s `ctors`, or declare it a nested source on its carrying parent.';
$out[] = '';
$out[] = '## Counts';
$out[] = '';
$out[] = '| kind | constructors | what it means for storage |';
$out[] = '|---|---:|---|';
$out[] = sprintf('| `update-carrier` | %d | an RPC RESULT carrying `Vector<Update>` — **each member must be unwrapped and placed**; the carrier writes no row of its own |', $counts[EndpointCoverage::KIND_UPDATE_CARRIER] ?? 0);
$out[] = sprintf('| `rpc-result` | %d | an RPC RESULT carrying no `Update` (`updates.state`, `updatesTooLong`, the `*Empty`/`*TooLong` results) — **no `tf_updates` row owed** |', $counts[EndpointCoverage::KIND_RPC_RESULT] ?? 0);
$out[] = sprintf('| `root-fact` | %d | the ctor IS a catalogued table\'s own row type |', $counts[EndpointCoverage::KIND_ROOT_FACT] ?? 0);
$out[] = sprintf('| `nested-source` | %d | the ctor rides on a catalogued parent\'s row |', $counts[EndpointCoverage::KIND_NESTED_SOURCE] ?? 0);
$out[] = sprintf('| `log-only` | %d | scalars placed via a catalog entry, no deeper edge |', $counts[EndpointCoverage::KIND_LOG_ONLY] ?? 0);
$out[] = sprintf('| `unmodelled` | %d | reaches `tf_updates` only — **the backlog** |', $counts[EndpointCoverage::KIND_UNMODELLED] ?? 0);
$out[] = sprintf('| **total** | **%d** | every `update*` constructor in the scheme |', array_sum($counts));
$out[] = '';
$out[] = '### Measured support for the two zeros, so they are not read as stubs';
$out[] = '';
$out[] = '- **`root-fact` = '.$counts[EndpointCoverage::KIND_ROOT_FACT].'** because NO catalog entry declares ANY';
$out[] = '  `update*` constructor in its `ctors` list. Measured now, from the loaded catalog:';
$out[] = '  **'.$catalogUpdateCtors.'** `update*` ctors appear across all entry `ctors` lists.';
$out[] = '  The nine `update*` names that appear in `mirror-catalog.json` are the **parent**';
$out[] = '  constructors of nested-source declarations on the `Update` type — not tables\' own row';
$out[] = '  types. That is a different fact, and conflating the two is what makes a coverage claim';
$out[] = '  look better than it is.';
$out[] = '- **`nested-source` = '.$counts[EndpointCoverage::KIND_NESTED_SOURCE].'** because no declared nested source';
$out[] = '  carries an object whose constructors are `update*`. All **'.$declaredNestedSources.'** declared';
$out[] = '  nested sources carry plain object types (`ChannelParticipant`, `BotInfo`, `MessageMedia`, …).';
$out[] = '  The carried ctors are derived from each source\'s resolved param type against the';
$out[] = '  same scheme — not guessed.';
$out[] = '- **`log-only` = '.$counts[EndpointCoverage::KIND_LOG_ONLY].'** because "reaches `tf_updates` and nothing deeper" is';
$out[] = '  exactly what `unmodelled` already names. Naming it twice would make the counts lie.';
$out[] = '  `log-only` is reserved for a catalog entry that DOES place a ctor\'s scalars but declares';
$out[] = '  no deeper edge, and none is measured to exist. Widening it to make the number look';
$out[] = '  better would be manufacturing coverage.';
$out[] = '';

foreach (EndpointCoverage::KINDS as $kind) {
    $rows = $byKind[$kind] ?? [];
    if ($rows === []) {
        continue;
    }
    $out[] = '## '.$kind.' ('.count($rows).')';
    $out[] = '';
    $out[] = '| constructor | tables | reason |';
    $out[] = '|---|---|---|';
    foreach ($rows as $e) {
        $out[] = sprintf('| `%s` | %s | %s |', $e['ctor'], implode(', ', array_map(
            static fn (string $t): string => '`'.$t.'`',
            $e['tables'],
        )), str_replace('|', '\\|', $e['reason']));
    }
    $out[] = '';
}

$out[] = '## Honest limits';
$out[] = '';
$out[] = '- **Reachability is not proven by this document.** A constructor classified';
$out[] = '  `nested-source` is declared as an edge; whether a realistic payload ever';
$out[] = '  stands on it is a separate, stronger question, and';
$out[] = '  `tests/Ingest/EveryCataloguedTableIsReachableTest.php` is the gate that asks it.';
$out[] = '- **`tf_updates` presence is not modelled here.** The generic fact log accepts any';
$out[] = '  constructor; Phase 3 of the plan proves that by inserting each one.';
$out[] = '- **This says nothing about a constructor\'s FIELDS.** Column-level coverage is';
$out[] = '  `tests/Schema/Mirror/ResolvedColumnsMatchShippedDdlTest.php` (D-007).';
$out[] = '- **The `update*` name prefix is not the same thing as "is an update".**';
$out[] = '  '.($counts[EndpointCoverage::KIND_UPDATE_CARRIER] + $counts[EndpointCoverage::KIND_RPC_RESULT]).' of the';
$out[] = '  '.$universe.' constructors named `update*` are RPC RESULTS — the reply to an';
$out[] = '  `updates.getDifference` / `updates.getChannelDifference` call, or a state snapshot. They are';
$out[] = '  classified `update-carrier` or `rpc-result` above, from their DECLARED result type and';
$out[] = '  `Vector<Update>` parameters, and they are still counted: the partition is total, so nothing';
$out[] = '  is excluded to make a count agree.';
$out[] = '- **`update-carrier` writes no row of its own, by design.** A `tf_updates` row naming';
$out[] = '  `updates` would record a thing that never happened as though it were an update. The gate is';
$out[] = '  `tests/Ingest/EveryClassifiedEndpointIngestsTest.php`, which asserts per kind: a carrier\'s';
$out[] = '  members must land, an `rpc-result` owes nothing, and every other kind owes its own row.';
$out[] = '';

$doc = implode("\n", $out);
$path = $root.'/docs/schema/endpoint-coverage.md';

if ($check) {
    $existing = is_file($path) ? (string) file_get_contents($path) : '';
    if ($existing !== $doc) {
        fwrite(STDERR, "STALE: {$path} does not match a fresh classification.\n");
        fwrite(STDERR, "Run: php bin/generate-endpoint-coverage.php\n");
        exit(1);
    }
    echo "current\n";
    exit(0);
}

file_put_contents($path, $doc);
echo "wrote {$path} (".count($report->endpoints())." endpoints)\n";
foreach ($counts as $kind => $n) {
    echo "  {$kind}: {$n}\n";
}
echo "  universe (parsed update* ctors): {$universe}\n";
echo "  tl lines matching ^update: {$tlLinesMatchingUpdatePrefix}\n";
echo "  update-named METHODS excluded: {$methodsNamedLikeUpdates}\n";
