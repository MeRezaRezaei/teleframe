<?php

declare(strict_types=1);

namespace MeRezaRezaei\Teleframe\Mirror\Models;

use Illuminate\Database\Eloquent\Relations\BelongsTo;
use MeRezaRezaei\Teleframe\Schema\Eloquent\AccountScoped;
use MeRezaRezaei\Teleframe\Schema\Eloquent\TfChildModel;
use MeRezaRezaei\Teleframe\Schema\Generated\Models\TlWallpaper;

/**
 * NF5 mirror of the WallPaper `settings` fact — table tf_wallpapers_settings
 * (2026_09_29_000100:90).
 *
 * WHY THIS IS A TABLE. mirror-catalog.json lists `settings` under
 * tf_wallpapers.children as "FK→WallPaperSettings": the fact is a nested TL
 * OBJECT, not a scalar, so it cannot become a parent column and becomes its own
 * child table instead.
 *
 * 1:1 FACT. The key is the wallPaper's own `id` — the settings object carries no
 * separate identifier, and the DDL primary key is (account_id, id)
 * (2026_09_29_000100:103). There is no `position` and none belongs in the key,
 * so this is not one of the plural vector children.
 *
 * KEY. The real primary key is COMPOSITE (account_id, id); Eloquent has one key
 * slot, so the non-account half `id` is the scalar key — faithful here because
 * `id` IS unique per wallPaper, and identical to the default `parent_id` of
 * TfChildModel in meaning, so it is stated explicitly rather than inherited
 * (same ruling as TfDialogFilterColor). Composite-key behaviour is inherently
 * PARTIAL: getKey() and find() are ambiguous across accounts, so address a row
 * by its natural (account_id, id). No autoincrement, no timestamps — the
 * curated dial is deliberately timestamp-free.
 *
 * WHY THE PARENT IS THE GENERATED TlWallpaper AND NOT A SECOND HAND-AUTHORED
 * MODEL. `tf_wallpapers` is already bound by exactly one class,
 * \MeRezaRezaei\Teleframe\Schema\Generated\Models\TlWallpaper (a generated
 * model in another namespace, regenerated by `teleframe:regenerate`). Adding a
 * second hand-authored model for the SAME table would create two roots for one
 * table and no Eloquent way to choose between them, so the settings child
 * attaches to the binding that exists. The cost of that choice is the one
 * cross-namespace reference below — the first in this directory — and it is
 * safe because the generated class is a deterministic function of the schema,
 * not an authored artefact that can drift. `TlWallpaper::$table` is
 * 'tf_wallpapers' and its key is 'id', so the relation is a one-column match on
 * both sides.
 *
 * @property int $account_id
 * @property int $id
 * @property bool $blur
 * @property bool $motion
 * @property int $background_color
 * @property int $second_background_color
 * @property int $third_background_color
 * @property int $fourth_background_color
 * @property int $intensity
 * @property int $rotation
 * @property string $emoticon
 */
final class TfWallpaperSettings extends TfChildModel
{
    use PinsDeclaredForeignKeyLegs;

    use AccountScoped;

    protected $table = 'tf_wallpapers_settings';

    protected $primaryKey = 'id';

    protected $guarded = [];

    protected $casts = [
        'account_id' => 'integer',
        'id' => 'integer',
        'blur' => 'boolean',
        'motion' => 'boolean',
        'background_color' => 'integer',
        'second_background_color' => 'integer',
        'third_background_color' => 'integer',
        'fourth_background_color' => 'integer',
        'intensity' => 'integer',
        'rotation' => 'integer',
    ];

    public function wallpaper(): BelongsTo
    {
        return $this->belongsTo(TlWallpaper::class, 'id', 'id');
    }
}