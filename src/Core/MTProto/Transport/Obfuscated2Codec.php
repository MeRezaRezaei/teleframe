<?php

declare(strict_types=1);

namespace MeRezaRezaei\Teleframe\Core\MTProto\Transport;

/**
 * The obfuscated2 (MTProto-style) transport codec — the transport-level side
 * of the control layer's relay terminal for NATIVE/desktop clients that can
 * speak raw TCP (browser clients cannot; they use /apiws, see the plans).
 *
 * Wire shape (no secret — the "accept" mode; matches the Telegram transport
 * obfuscation spec as implemented by TDesktop/MTProxy/GramJS): the client
 * opens a TCP connection and sends exactly 64 header bytes:
 *
 *   - bytes 0-7   random (first byte must not be 0xef; bytes 0-4 must not
 *                 collide with a plain-transport init marker; bytes 4-8
 *                 must not be all zero)
 *   - bytes 8-56  48 random bytes the keys are derived from
 *   - bytes 56-60 protocol tag, ENCRYPTED with the from-client keystream:
 *                 0xEFEFEFEF=abridged, 0xEEEEEEEE=intermediate,
 *                 0xDDDDDDDD=secure-intermediate
 *   - bytes 60-62 DC id as little-endian int16, ENCRYPTED likewise
 *   - bytes 62-64 random padding, ENCRYPTED likewise
 *
 * Key/IV derivation (no secret):
 *   from-client (server decrypt): key = header[8:40],   iv = header[40:56]
 *   to-client   (server encrypt): key = rev[0:32],      iv = rev[32:48]
 *     where rev = reverse(header[8:56]) — one 48-byte blob reversal
 *
 * The encrypted tail is decrypted with the from-client AES-256-CTR keystream
 * at offset 56 (the client encrypts the full 64-byte header with its
 * to-server cipher and keeps only bytes 56-64), so payload traffic continues
 * at keystream offset 64 in that direction. Straightforward string functions
 * only — zero regex, per the src/Core discipline.
 *
 * Auth note (W-10): this codec alone authenticates nobody — the "accept"
 * mode is an anonymous byte proxy by itself. RelayServer supports an
 * optional pre-header HMAC guard (acceptSecret / acceptToken) for raw TCP
 * listeners; when the codec's parseHeader is used by a client leg without
 * that guard, the listener must stay loopback-bound or be keyed, or it is
 * an open proxy.
 */
class Obfuscated2Codec
{
    public const HEADER_SIZE = 64;

    public const PROTOCOL_ABRIDGED = 'abridged';

    public const PROTOCOL_INTERMEDIATE = 'intermediate';

    public const PROTOCOL_SECURE_INTERMEDIATE = 'secure-intermediate';

    /** @var array<string, string> encrypted tag (header bytes 56-60) per protocol */
    private const TAGS = [
        self::PROTOCOL_ABRIDGED => "\xEF\xEF\xEF\xEF",
        self::PROTOCOL_INTERMEDIATE => "\xEE\xEE\xEE\xEE",
        self::PROTOCOL_SECURE_INTERMEDIATE => "\xDD\xDD\xDD\xDD",
    ];

    /**
     * Plain-transport / HTTP / TLS init markers that must never prefix an
     * obfuscated2 header (transport-obfuscation spec, as generated by the
     * vendored GramJS FORBIDDEN_OBFUSCATED_PREFIXES): a peer that opens with
     * one of these is not an obfuscated2 client.
     *
     * @var list<string>
     */
    private const FORBIDDEN_PREFIXES = [
        'HEAD', // HTTP method probes
        'POST',
        'GET ',
        'OPTI',
        "\x16\x03\x01\x02", // TLS ClientHello
        "\xDD\xDD\xDD\xDD", // secure-intermediate cleartext init tag
        "\xEE\xEE\xEE\xEE", // intermediate cleartext init tag
    ];

    /**
     * Parses and validates a raw obfuscated2 connection header.
     *
     * @return array{
     *     dc_id: int,
     *     protocol: string,
     *     decryptKey: string,
     *     encryptKey: string,
     *     decryptIv: string,
     *     encryptIv: string,
     * }
     *
     * @throws Obfuscated2Exception on wrong length, a header-sanity violation
     *                              (leading 0xEF, a plain-transport init
     *                              collision in bytes 0-4, or bytes 4-8 all
     *                              zero), or an encrypted tag that matches no
     *                              known transport
     */
    public static function parseHeader(string $header): array
    {
        if (strlen($header) !== self::HEADER_SIZE) {
            throw new Obfuscated2Exception(
                'Obfuscated2Codec: header must be exactly '.self::HEADER_SIZE.' bytes, got '.strlen($header)
            );
        }

        // Header-sanity guards (transport-obfuscation spec): before any key
        // derivation, reject headers that are obviously a plain-abridged
        // connection, a cleartext intermediate/secure-init, an HTTP/TLS
        // probe, or a degenerate all-zero keystream window.
        if ($header[0] === "\xEF") {
            throw new Obfuscated2Exception(
                'Obfuscated2Codec: header leads with 0xEF, the plain-abridged init byte'
            );
        }
        if (substr($header, 4, 4) === "\0\0\0\0") {
            throw new Obfuscated2Exception(
                'Obfuscated2Codec: header bytes 4-8 are all zero (degenerate keystream window)'
            );
        }
        if (in_array(substr($header, 0, 4), self::FORBIDDEN_PREFIXES, true)) {
            throw new Obfuscated2Exception(
                'Obfuscated2Codec: header collides with a plain-transport init marker (0x'.bin2hex(substr($header, 0, 4)).')'
            );
        }

        // Raw key material: one 48-byte window, read forward for the
        // from-client direction and reversed as a whole for the to-client
        // direction (per the transport obfuscation spec).
        $window = substr($header, 8, 48);
        $reversed = strrev($window);

        $decryptKey = substr($window, 0, 32);
        $decryptIv = substr($window, 32, 16);
        $encryptKey = substr($reversed, 0, 32);
        $encryptIv = substr($reversed, 32, 16);

        // The tail (bytes 56-64) travels encrypted with the from-client
        // keystream at offset 56 — the client ran its whole 64-byte header
        // through the cipher and kept only the encrypted tail.
        $tail = Obfuscated2Cipher::xcryptAt(
            substr($header, 56, 8),
            $decryptKey,
            $decryptIv,
            56,
        );

        $tag = substr($tail, 0, 4);
        $protocol = array_search($tag, self::TAGS, true);
        if ($protocol === false) {
            throw new Obfuscated2Exception(
                'Obfuscated2Codec: invalid obfuscated2 magic — decrypted tag 0x'.bin2hex($tag)
            );
        }

        // DC id: little-endian int16 at decrypted bytes 60-62 (test DCs can
        // be negative; bytes 62-64 are padding the client chose).
        $dcId = unpack('v', substr($tail, 4, 2))[1];
        if ($dcId > 0x7FFF) {
            $dcId -= 0x10000;
        }

        return [
            'dc_id' => $dcId,
            'protocol' => $protocol,
            'decryptKey' => $decryptKey,
            'encryptKey' => $encryptKey,
            'decryptIv' => $decryptIv,
            'encryptIv' => $encryptIv,
        ];
    }
}
